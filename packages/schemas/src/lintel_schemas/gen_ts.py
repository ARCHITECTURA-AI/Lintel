"""Generate TypeScript types from the Pydantic models.

Run `uv run lintel-gen-ts` (or `python -m lintel_schemas.gen_ts`). The output is committed at
apps/web/src/lib/schemas.gen.ts, and a test fails if it drifts from the models.
"""

from __future__ import annotations

import inspect
import sys
from enum import StrEnum
from pathlib import Path
from typing import Any

from pydantic import BaseModel
from pydantic.json_schema import models_json_schema

from . import enums, lifecycle, models

OUT = Path(__file__).resolve().parents[4] / "apps" / "web" / "src" / "lib" / "schemas.gen.ts"


def _enum_classes() -> list[type[StrEnum]]:
    return [
        obj
        for _, obj in inspect.getmembers(enums, inspect.isclass)
        if issubclass(obj, StrEnum) and obj is not StrEnum
    ]


def _model_classes() -> list[type[BaseModel]]:
    return [
        obj
        for _, obj in inspect.getmembers(models, inspect.isclass)
        if issubclass(obj, BaseModel) and obj.__module__ == models.__name__ and obj is not models.Strict
    ]


def _ts_type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "enum" in schema:
        return " | ".join(f'"{v}"' for v in schema["enum"])
    if "const" in schema:
        return f'"{schema["const"]}"'
    for key in ("anyOf", "oneOf"):
        if key in schema:
            parts = []
            for s in schema[key]:
                t = _ts_type(s)
                if t not in parts:
                    parts.append(t)
            return " | ".join(parts)
    t = schema.get("type")
    if t == "string":
        return "string"
    if t in ("integer", "number"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    if t == "array":
        inner = _ts_type(schema.get("items", {}))
        return f"Array<{inner}>"
    if t == "object":
        add = schema.get("additionalProperties")
        if isinstance(add, dict) and add:
            return f"Record<string, {_ts_type(add)}>"
        return "Record<string, unknown>"
    return "unknown"


def render() -> str:
    lines = [
        "// Generated by packages/schemas (lintel_schemas.gen_ts). Do not edit by hand.",
        "/* eslint-disable */",
        "",
    ]
    for enum_cls in sorted(_enum_classes(), key=lambda c: c.__name__):
        values = " | ".join(f'"{m.value}"' for m in enum_cls)
        lines.append(f"export type {enum_cls.__name__} = {values};")
        lines.append(
            f"export const {enum_cls.__name__}Values = [{', '.join(repr(m.value).replace(chr(39), chr(34)) for m in enum_cls)}] as const;"
        )
    lines.append("")

    _, schema = models_json_schema([(m, "serialization") for m in _model_classes()], ref_template="#/$defs/{model}")
    defs = schema.get("$defs", {})
    enum_names = {c.__name__ for c in _enum_classes()}
    for name in sorted(defs):
        if name in enum_names:
            continue
        d = defs[name]
        if "enum" in d:
            lines.append(f"export type {name} = {_ts_type(d)};")
            continue
        lines.append(f"export interface {name} {{")
        required = set(d.get("required", []))
        for prop, ps in d.get("properties", {}).items():
            opt = "" if prop in required else "?"
            lines.append(f"  {prop}{opt}: {_ts_type(ps)};")
        lines.append("}")
        lines.append("")

    S = enums.ApplicationState
    lines.append("export const TERMINAL_STATES: ApplicationState[] = [")
    lines.append("  " + ", ".join(f'"{s.value}"' for s in sorted(lifecycle.TERMINAL_STATES, key=list(S).index)))
    lines.append("];")
    lines.append("export const GATE_STATES: ApplicationState[] = [")
    lines.append("  " + ", ".join(f'"{s.value}"' for s in sorted(lifecycle.GATE_STATES, key=list(S).index)))
    lines.append("];")
    lines.append("export const HAPPY_PATH: ApplicationState[] = [")
    lines.append("  " + ", ".join(f'"{s.value}"' for s in lifecycle.HAPPY_PATH))
    lines.append("];")
    lines.append("export const STATE_LABELS: Record<ApplicationState, string> = {")
    for s, label in lifecycle.STATE_LABELS.items():
        lines.append(f'  {s.value}: "{label}",')
    lines.append("};")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    text = render()
    if "--check" in sys.argv:
        current = OUT.read_text() if OUT.exists() else ""
        if current != text:
            print(f"{OUT} is out of date. Run: uv run lintel-gen-ts", file=sys.stderr)
            sys.exit(1)
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
